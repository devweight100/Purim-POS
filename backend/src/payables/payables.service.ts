/** A supplier bill becomes a payable only after goods were received (accrual on receipt). */
export const PAYABLE_PO_STATUSES: POStatus[] = [POStatus.PARTIALLY_RECEIVED, POStatus.RECEIVED, POStatus.COMPLETED];

/** Amount that can still be paid now: never more than the value of goods actually received. */
export function payableNow(po: { totalAmount: any; paidAmount: any; remainingPayable: any; items?: { receivedQty: unknown; unitCost: any; quantity?: unknown; total?: any }[] }): number {
  const remaining = Number(po.remainingPayable) || 0;
  if (!po.items) return Math.max(0, remaining);
  // value of goods received so far, incl. discounts and VAT of each line
  const receivedValue = po.items.reduce(
    (sum, i) => sum + Number(i.receivedQty) * (Number(i.quantity) && i.total !== undefined ? grossPerUnit({ quantity: i.quantity, total: i.total, unitCost: i.unitCost }) : Number(i.unitCost)),
    0,
  );
  const cap = Math.round((receivedValue - Number(po.paidAmount || 0)) * 100) / 100;
  return Math.max(0, Math.min(remaining, cap));
}

import { IsString, IsNotEmpty, IsArray, IsOptional, IsNumber, IsIn, ValidateNested, Matches } from 'class-validator';
import { Type } from 'class-transformer';

/** Real money methods a supplier can be paid with (credit sale / credit note / card are not money out). */
export const SUPPLIER_PAYMENT_METHODS: PaymentMethod[] = [PaymentMethod.CASH, PaymentMethod.TRANSFER, PaymentMethod.QR_PROMPTPAY];

/** Parse and check a voucher payment date: valid and not in the future (10 min clock tolerance). */
export function parsePaymentDate(raw: any, now = new Date()): Date {
  if (raw === undefined || raw === null || raw === '') return now;
  const d = new Date(raw);
  if (typeof raw !== 'string' || Number.isNaN(d.getTime()) || d.getFullYear() < 2000) throw new BadRequestException('วันที่จ่ายเงินไม่ถูกต้อง');
  if (d.getTime() > now.getTime() + 10 * 60 * 1000) throw new BadRequestException('วันที่จ่ายเงินต้องไม่เป็นวันในอนาคต');
  return d;
}

